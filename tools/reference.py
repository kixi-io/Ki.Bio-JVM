"""Ki.Bio's test reference values from Biopython: Tm, pI, translation under all NCBI codes, masses.

Usage (from the repository root): python3 -I tools/reference.py src/test/resources/io/kixi/bio/biopython-reference.tsv
Needs Biopython (pip install biopython); the output is deterministic for a given Biopython version.
"""
import sys, random, Bio
from Bio.SeqUtils import MeltingTemp as mt
from Bio.SeqUtils.IsoelectricPoint import IsoelectricPoint
from Bio.SeqUtils import molecular_weight
from Bio.Seq import Seq
from Bio.Data import CodonTable

rnd = random.Random(20261024)
out = [f"# Generated by reference.py with Biopython {Bio.__version__}; seed 20261024. Do not edit by hand."]

def revcomp(s):
    return s[::-1].translate(str.maketrans("ACGT", "TGCA"))

# Tm: kind<TAB>seq<TAB>Na mM<TAB>Mg mM<TAB>dNTP mM<TAB>oligo nM<TAB>Tm °C
primers = ["GTAAAACGACGGCCAGT", "TAATACGACTCACTATAGGG", "ATTATTAAATAATTTAAT", "AGCGGATAACAATTTCACACAGG",
           "CAGGAAACAGCTATGAC", "GCGCGCATATATGCGC", "ACGTACGT", "GCGCGATCG", "ATGACCATGATTACGGATTC", "GAATTC", "AT"]
for _ in range(120):
    n = rnd.randint(8, 40)
    primers.append("".join(rnd.choice("ACGT") for _ in range(n)))
conds = [(50, 0, 0, 250), (50, 1.5, 0.2, 250), (50, 3, 0.8, 500), (100, 0, 0, 100), (10, 2, 0, 250), (0, 2, 0, 250),
         (200, 10, 1, 1000), (50, 0.5, 0, 250), (25, 6, 0.2, 50)]
for p in primers:
    for (na, mg, dntp, oligo) in conds:
        self = p == revcomp(p)
        if self:
            tm = mt.Tm_NN(p, nn_table=mt.DNA_NN3, Na=na, Mg=mg, dNTPs=dntp, dnac1=oligo, dnac2=0, saltcorr=7, selfcomp=True)
        else:
            tm = mt.Tm_NN(p, nn_table=mt.DNA_NN3, Na=na, Mg=mg, dNTPs=dntp, dnac1=oligo, dnac2=0, saltcorr=7)
        out.append(f"tm\t{p}\t{na}\t{mg}\t{dntp}\t{oligo}\t{tm!r}")

# pI: pI<TAB>protein<TAB>pI (Biopython IsoelectricPoint, ExPASy's method), and the charge at pH 7
aas = "ACDEFGHIKLMNPQRSTVWY"
prots = ["MKTAYIAKQRQISFVKSHFSRQ", "MQIFVKTLTGKTITLEVEPSDTIENVKAKIQDKEGIPPDQQRLIFAGKQLEDGRTLSDYNIQKESTLHLVLRLRGG",
         "PEPTIDE", "DDDDEEEE", "KKKKRRRR", "FVNQHLCGSHLVEALYLVCGERGFFYTPKT", "A", "C", "P", "SKTAYIAKQRQISFVKSHFSRE"]
for _ in range(150):
    prots.append("".join(rnd.choice(aas) for _ in range(rnd.randint(1, 300))))
for p in prots:
    ip = IsoelectricPoint(p)
    out.append(f"pI\t{p}\t{ip.pi()!r}\t{ip.charge_at_pH(7.0)!r}")

# Translation: code<TAB>id<TAB>dna<TAB>protein (all three frames of plain DNA)
for t in sorted(CodonTable.unambiguous_dna_by_id):
    for _ in range(4):
        s = "".join(rnd.choice("ACGT") for _ in range(rnd.randint(30, 90)))
        for f in range(3):
            sub = s[f:]
            sub = sub[: len(sub) // 3 * 3]
            out.append(f"code\t{t}\t{f + 1}\t{s}\t{Seq(sub).translate(table=t)}")

# Average masses as Biopython computes them (its own weights): mass<TAB>kind<TAB>seq<TAB>Da
for _ in range(40):
    s = "".join(rnd.choice("ACGT") for _ in range(rnd.randint(1, 120)))
    out.append(f"mass\tDNA\t{s}\t{molecular_weight(s, 'DNA')!r}")
    r = s.replace("T", "U")
    out.append(f"mass\tRNA\t{r}\t{molecular_weight(r, 'RNA')!r}")
    p = "".join(rnd.choice(aas) for _ in range(rnd.randint(1, 300)))
    out.append(f"mass\tProtein\t{p}\t{molecular_weight(p, 'protein')!r}")

open(sys.argv[1], "w").write("\n".join(out) + "\n")
